#!/usr/bin/env node
/* Freeze the current player pool as the test fixture.
 *
 *     node bin/fixture.mjs --user taylars [--league <id>] [--season 2026]
 *
 * The recommendation tests need a pool that does not move. Sleeper's
 * projections and ADP change every day, and grades change every time someone
 * researches a batch, so a test that fetched either would pass or fail for
 * reasons that have nothing to do with the formula. This writes the pool down
 * once, into test/fixtures/pool.json, and the tests read that.
 *
 * What it stores is the *priced* pool — buildPool's output, not Sleeper's
 * response — because that is the input the value formula actually takes. It
 * keeps the fixture to a hundred kilobytes instead of three megabytes, and it
 * means a change to scoring or grading cannot quietly rewrite what the
 * recommendation tests are asserting against. The cost is that this file has to
 * be regenerated by hand when the pool is meant to move; that is the point.
 *
 * Regenerating needs a Sleeper account, because the pool is priced under a real
 * league's scoring settings. The committed fixture does not — it is plain
 * numbers, and the tests run offline.
 */

import { writeFile } from "node:fs/promises";
import { loadLocalGrades } from "./lib/grades.mjs";
import { SleeperClient } from "../js/sleeper.js";
import { FileCache } from "../js/cache-fs.js";
import { buildPool, draftShape, draftFormat } from "../js/pool.js";

const OUT = "test/fixtures/pool.json";

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    if (flag.startsWith("--")) args[flag.slice(2)] = argv[++i];
  }
  return args;
}

/* One player per line.
 *
 * JSON.stringify's own indenting spreads five hundred players over six thousand
 * lines, where every regeneration reads as a rewrite of the whole file. A line
 * per player means a diff shows the players that actually changed.
 */
function serialize(fixture) {
  const { players, ...head } = fixture;
  const lines = players.map((p) => `  ${JSON.stringify(p)}`).join(",\n");
  return `{\n${Object.entries(head).map(([k, v]) => ` ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n")},\n "players": [\n${lines}\n ]\n}\n`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.user) {
    console.error("usage: node bin/fixture.mjs --user <sleeper username> [--league id] [--season year]");
    process.exit(2);
  }

  const sleeper = new SleeperClient({ cache: new FileCache() });
  const { grades, season: gradeSeason } = await loadLocalGrades();

  const user = await sleeper.getUser(args.user);
  if (!user) { console.error(`no such Sleeper user: ${args.user}`); process.exit(1); }

  const season = args.season ?? (await sleeper.getState()).season;
  const leagues = await sleeper.getUserLeagues(user.user_id, season);
  const league = args.league ? leagues.find((l) => l.league_id === args.league) : leagues[0];
  if (!league) { console.error(`no league ${args.league ?? ""} for ${args.user} in ${season}`); process.exit(1); }

  const drafts = await sleeper.getLeagueDrafts(league.league_id);
  const draft = drafts.length ? draftShape(drafts[0]) : null;
  const pool = buildPool(await sleeper.getProjections(season), grades, league, draft);

  const fixture = {
    generated: new Date().toISOString().slice(0, 10),
    season: String(season),
    grades_season: gradeSeason,
    league: league.name,
    format: draftFormat(league, draft),
    // The starting lineup the tests price against. Teams and rounds decide the
    // replacement baselines, so they belong to the fixture rather than to a
    // scenario that is only choosing where we sit.
    slots: league.roster_positions ?? [],
    teams: draft?.teams ?? league.total_rosters ?? 12,
    rounds: draft?.rounds ?? (league.roster_positions ?? []).length,
    players: pool,
  };

  await writeFile(OUT, serialize(fixture));
  const graded = pool.filter((p) => p.graded).length;
  console.log(`${OUT}: ${pool.length} players (${graded} graded), ${fixture.league} ${fixture.season} ${fixture.format}`);
  console.log(`  ${fixture.teams} teams, ${fixture.rounds} rounds, slots ${fixture.slots.join("/")}`);
}

main().catch((err) => { console.error(err); process.exit(1); });
